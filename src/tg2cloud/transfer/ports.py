from __future__ import annotations

from collections.abc import Callable, Iterable
from dataclasses import dataclass
from pathlib import Path
from typing import Any, Protocol

from tg2cloud.domain.models import StagingScan


@dataclass(frozen=True)
class DestinationProbe:
    accessible: bool
    scope: str
    detail: str
    failure_kind: str = ""


class MediaSource(Protocol):
    """Authorized media access; ingestion must still use the shared TaskDB."""

    async def get_messages(self, entity: int, *, ids: int) -> Any: ...

    async def download_media(
        self, message: Any, *, file: Any,
        progress_callback: Callable[[int, int], None],
    ) -> Any: ...


class TaskRepository(Protocol):
    """Persistence owns atomic transitions/reservations; callers never split them."""

    def get(self, task_id: int) -> dict[str, Any] | None: ...
    def create_task(self, **fields: Any) -> tuple[dict[str, Any], bool]: ...
    def reserve(self, task_id: int, **limits: Any) -> tuple[bool, str]: ...
    def transition(self, task_id: int, new_state: str, **fields: Any) -> None: ...
    def update(self, task_id: int, **fields: Any) -> None: ...
    def requeue(self, task_id: int, **conditions: Any) -> bool: ...
    def recover(self, download_dir: Path, **conditions: Any) -> dict[str, int]: ...
    def remote_claimed(self, path: str, task_id: int) -> bool: ...
    def protected_remote(self, path: str) -> bool: ...
    def staging_name(self, task_id: int, safe_name: str) -> str: ...
    def counts(self) -> dict[str, int]: ...
    def is_paused(self) -> bool: ...
    def used_local_bytes(self) -> int: ...
    def list_states(self, states: Iterable[str], *, limit: int = 200, ready_only: bool = False, after_id: int = 0) -> list[dict[str, Any]]: ...
    def close(self) -> None: ...


class UploadStream(Protocol):
    async def write(self, data: bytes) -> int: ...
    def tell(self) -> int: ...
    def flush(self) -> None: ...
    async def finish(self) -> None: ...
    async def abort(self) -> None: ...


class Destination(Protocol):
    """Size verification is backend receipt, not final cloud-provider confirmation."""

    async def probe(self) -> DestinationProbe: ...
    async def healthy(self) -> bool: ...
    async def upload(
        self, local_path: Path, remote_temp: str,
        *, progress: Callable[[int, float], None] | None = None,
    ) -> None: ...
    async def open_upload_stream(
        self, remote_temp: str, exact_size: int,
    ) -> UploadStream: ...
    async def remote_size(self, relative_path: str) -> int: ...
    async def exists(self, relative_path: str) -> bool: ...
    async def move(self, source: str, destination: str) -> None: ...
    async def remove(self, relative_path: str) -> None: ...
    async def list_staging_objects(self) -> StagingScan: ...
